-- Starter schema for future production Supabase integration.
create table if not exists public.products (
 id bigint generated by default as identity primary key,
 name text not null, description text, price numeric(12,2) not null default 0,
 old_price numeric(12,2), category text, stock integer not null default 0,
 image_url text, created_at timestamptz default now()
);
create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text, phone text, is_admin boolean not null default false,
 created_at timestamptz default now()
);
create table if not exists public.orders (
 id bigint generated by default as identity primary key,
 user_id uuid references auth.users(id) on delete set null,
 total numeric(12,2) not null default 0, status text not null default 'pending',
 created_at timestamptz default now()
);
create table if not exists public.order_items (
 id bigint generated by default as identity primary key,
 order_id bigint references public.orders(id) on delete cascade,
 product_id bigint references public.products(id) on delete set null,
 quantity integer not null default 1, price numeric(12,2) not null default 0
);
create table if not exists public.wishlists (
 id bigint generated by default as identity primary key,
 user_id uuid references auth.users(id) on delete cascade,
 product_id bigint references public.products(id) on delete cascade,
 created_at timestamptz default now(),
 unique(user_id,product_id)
);
